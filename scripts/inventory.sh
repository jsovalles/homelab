#!/usr/bin/env bash
# Render the Ansible inventory for an environment from the OpenTofu variables
# (local.ansible_inventory). Uses `tofu console`, so no applied state is needed.
#
# Usage: scripts/inventory.sh <prod|test>
set -Eeuo pipefail

REPO_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
env_name="${1:?usage: $0 <prod|test>}"
out="$REPO_ROOT/infrastructure/ansible/inventory/${env_name}.yml"
tmp="$(mktemp)"
trap 'rm -f -- "$tmp"' EXIT

# The inventory depends only on variables, never on state. Point the console at an empty,
# non-existent state: OpenTofu 1.12's console ignores the selected workspace and would read
# the default (production) state otherwise.
echo 'nonsensitive(jsonencode(local.ansible_inventory))' \
  | "$REPO_ROOT/scripts/tofu.sh" "$env_name" console -lock=false -state="${tmp}.nostate" >"$tmp"

python3 - "$tmp" "$out" <<'PY'
import json, sys
# The value is the last line printed by `tofu console` (a quoted JSON string)
raw = [l for l in open(sys.argv[1]).read().splitlines() if l.startswith('"')][-1]
inventory = json.loads(json.loads(raw))  # console prints a quoted JSON string
with open(sys.argv[2], "w") as f:
    f.write("# GENERATED by scripts/inventory.sh from infrastructure/terraform – do not edit\n")
    json.dump(inventory, f, indent=2, sort_keys=True)
    f.write("\n")
PY
printf 'inventory: wrote %s\n' "${out#"$REPO_ROOT"/}"
